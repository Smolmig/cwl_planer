export function groupReleasesByDate(items = releaseHistory){
 const groups=[];
 for(const item of items){
  let current=groups.at(-1);
  if(!current||current.date!==item.date){current={date:item.date,items:[]};groups.push(current)}
  current.items.push(item);
 }
 return groups;
}
